import React from 'react'
import './Hero.css'

/* Hero section: large serif headline with one italic word, one plain sentence.
   No badge, no gradient, no centered layout. */
export default function Hero() {
  const scrollTo = (e, id) => {
    e.preventDefault()
    document.getElementById(id)?.scrollIntoView({ behavior: 'smooth' })
  }

  return (
    <section id="hero" className="section section--hero">
      <div className="container hero">
        <h1 className="hero__headline">
          Is this face <em>real?</em>
        </h1>
        <p className="hero__sub">
          Upload a portrait and our model will estimate whether it was taken
          with a camera or generated by a machine. One model. Plain numbers.
        </p>
        <a
          href="#detector"
          className="hero__cta"
          onClick={(e) => scrollTo(e, 'detector')}
        >
          Try the detector
        </a>
      </div>
    </section>
  )
}
