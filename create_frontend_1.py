import pathlib
ROOT = pathlib.Path(r"E:\3D")
def w(rel, content):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    print("  wrote", rel)

# package.json
